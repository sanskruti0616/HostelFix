// Allowed status transitions mapping per role
const STATUS_TRANSITIONS = {
  // Student can cancel or reopen
  [ROLES.STUDENT]: {
    [COMPLAINT_STATUS.SUBMITTED]: [COMPLAINT_STATUS.CANCELLED],
    [COMPLAINT_STATUS.RESOLVED]: [COMPLAINT_STATUS.REOPENED, COMPLAINT_STATUS.CLOSED],
  },
  // Warden has broader control
  [ROLES.WARDEN]: {
    [COMPLAINT_STATUS.SUBMITTED]: [
      COMPLAINT_STATUS.PENDING_VERIFICATION,
      COMPLAINT_STATUS.VERIFIED,
      COMPLAINT_STATUS.ASSIGNED,
      COMPLAINT_STATUS.NEEDS_INFORMATION,
      COMPLAINT_STATUS.REJECTED,
    ],
    [COMPLAINT_STATUS.PENDING_VERIFICATION]: [
      COMPLAINT_STATUS.VERIFIED,
      COMPLAINT_STATUS.NEEDS_INFORMATION,
      COMPLAINT_STATUS.REJECTED,
      COMPLAINT_STATUS.ASSIGNED,
    ],
    [COMPLAINT_STATUS.VERIFIED]: [
      COMPLAINT_STATUS.ASSIGNED,
      COMPLAINT_STATUS.IN_PROGRESS,
      COMPLAINT_STATUS.REJECTED,
    ],
    [COMPLAINT_STATUS.ASSIGNED]: [
      COMPLAINT_STATUS.IN_PROGRESS,
      COMPLAINT_STATUS.VERIFIED,
      COMPLAINT_STATUS.CANCELLED,
    ],
    [COMPLAINT_STATUS.IN_PROGRESS]: [
      COMPLAINT_STATUS.NEED_MATERIAL,
      COMPLAINT_STATUS.CANNOT_COMPLETE,
      COMPLAINT_STATUS.RESOLVED,
    ],
    [COMPLAINT_STATUS.NEED_MATERIAL]: [
      COMPLAINT_STATUS.IN_PROGRESS,
      COMPLAINT_STATUS.CANNOT_COMPLETE,
    ],
    [COMPLAINT_STATUS.CANNOT_COMPLETE]: [
      COMPLAINT_STATUS.ASSIGNED,
      COMPLAINT_STATUS.REJECTED,
    ],
    [COMPLAINT_STATUS.RESOLVED]: [
      COMPLAINT_STATUS.CLOSED,
      COMPLAINT_STATUS.REOPENED,
    ],
    [COMPLAINT_STATUS.REOPENED]: [
      COMPLAINT_STATUS.ASSIGNED,
      COMPLAINT_STATUS.IN_PROGRESS,
    ],
    [COMPLAINT_STATUS.NEEDS_INFORMATION]: [
      COMPLAINT_STATUS.SUBMITTED,
      COMPLAINT_STATUS.REJECTED,
    ],
  },
  // Maintenance staff can transition active work
  [ROLES.STAFF]: {
    [COMPLAINT_STATUS.ASSIGNED]: [COMPLAINT_STATUS.IN_PROGRESS],
    [COMPLAINT_STATUS.IN_PROGRESS]: [
      COMPLAINT_STATUS.NEED_MATERIAL,
      COMPLAINT_STATUS.CANNOT_COMPLETE,
      COMPLAINT_STATUS.RESOLVED,
    ],
    [COMPLAINT_STATUS.NEED_MATERIAL]: [
      COMPLAINT_STATUS.IN_PROGRESS,
      COMPLAINT_STATUS.CANNOT_COMPLETE,
    ],
  },
  // Admin has full control
  [ROLES.ADMIN]: ALL_STATUSES.reduce((acc, status) => {
    acc[status] = ALL_STATUSES.filter((s) => s !== status)
    return acc
  }, {}),
  // Platform Admin has full cross-tenant control
  [ROLES.PLATFORM_ADMIN]: ALL_STATUSES.reduce((acc, status) => {
    acc[status] = ALL_STATUSES.filter((s) => s !== status)
    return acc
  }, {}),
}

